import assert from 'node:assert/strict';
import { createClient } from '@supabase/supabase-js';
const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
const key = process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY;
if (!url || !key) throw new Error('Missing isolated acceptance project URL/publishable key.');
const expected = { presenter: 8, analyst: 8, restricted: 6, reviewer: 8 };
const roles = { presenter: 'presenter_admin', analyst: 'full_analyst', restricted: 'restricted_analyst', reviewer: 'reviewer' };
const client = () => createClient(url,key,{ auth: { persistSession: false, autoRefreshToken: false } });
const anonymous = client();
const anon = await anonymous.from('records').select('id');
assert.ok(anon.error || anon.data.length === 0, 'Anonymous source reads denied');
for (const [name, count] of Object.entries(expected)) {
  const db = client();
  const password = process.env[`BASEERAT_${name.toUpperCase()}_PASSWORD`] || process.env.BASEERAT_ACCOUNT_PASSWORD;
  if (!password) throw new Error(`Missing acceptance password for ${name}.`);
  const login = await db.auth.signInWithPassword({ email: `${name}@baseerat.example`, password });
  assert.equal(login.error, null, `${name} real authentication`);
  const records = await db.from('records').select('id,source_id');
  assert.equal(records.error, null);
  assert.equal(records.data.length,count,`${name} source membership`);
  const profiles = await db.from('profiles').select('user_id,role');
  assert.equal(profiles.data.length,1, 'Self-only profile');
  assert.equal(profiles.data[0].role,roles[name]);
  const forged = await db.auth.updateUser({ data: { role: 'presenter_admin' } });
  assert.equal(forged.error,null);
  const forbidden = await db.from('records').select('*').eq('id','10000000-0000-4000-8000-000000000007');
  assert.equal(forbidden.error,null);
  assert.equal(forbidden.data.length,name === 'restricted' ? 0 : 1,'User metadata cannot grant a source');
  const writes = await db.from('profiles').update({ role: 'presenter_admin' }).eq('user_id',login.data.user.id);
  assert.ok(writes.error,'Ordinary users cannot edit authorization');
  const raw = await db.from('query_sessions').select('*');
  assert.ok(raw.error,'Raw sessions are absent from public Data API');
  const actions = await db.from('action_grants').select('action');
  assert.equal(actions.error,null);
  const available = actions.data.map(row => row.action);
  assert.equal(available.includes('admin'),name === 'presenter');
  assert.equal(available.includes('review'),name === 'presenter' || name === 'reviewer');
  await db.auth.signOut();
  console.log(`${name}: authenticated source/action/self-profile/forged-role/private-API/write denials passed.`);
}
